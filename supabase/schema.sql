-- ============================================================
-- 背单词工具 · Supabase 数据库初始化脚本
-- 在 Supabase 控制台 SQL Editor 中执行本文件即可建表
-- 数据模型：books → words → senses → examples（三层词条）+ scan_batches（扫描批次）
-- ============================================================

-- 1. 书籍表（为整本书扫描预留，第一版可只有一条记录）
CREATE TABLE IF NOT EXISTS public.books (
  id          TEXT PRIMARY KEY,              -- 自定义书 ID，如 'victor-123'
  name        TEXT NOT NULL,                 -- 书名，如 '维克多英语词汇书'
  cover_url   TEXT,
  created_at  TIMESTAMPTZ DEFAULT now()
);

-- 2. 词条表
CREATE TABLE IF NOT EXISTS public.words (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id       TEXT REFERENCES public.books(id) ON DELETE CASCADE,
  headword      TEXT NOT NULL,
  phonetic      TEXT,
  audio         BOOLEAN DEFAULT FALSE,
  level_tag     TEXT,
  inline_def    TEXT,
  countability  TEXT,
  source        TEXT,                        -- 词条级出处
  page_no       INTEGER,
  batch_id      BIGINT,                      -- 来源扫描批次
  created_at    TIMESTAMPTZ DEFAULT now(),
  UNIQUE(book_id, headword)                  -- 同一本书里单词唯一
);
CREATE INDEX IF NOT EXISTS idx_words_headword ON public.words (headword);
CREATE INDEX IF NOT EXISTS idx_words_book ON public.words (book_id);

-- 3. 义项表
CREATE TABLE IF NOT EXISTS public.senses (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id       BIGINT NOT NULL REFERENCES public.words(id) ON DELETE CASCADE,
  pos           TEXT,                        -- n. / vi. / adj. / adv.
  sense_no      INTEGER,                     -- ①②③ 编号
  countability  TEXT,                        -- [C] / [U] / [C]&[U]
  usage_label   TEXT,                        -- [常用单数] 等用法标签
  chinese_def   TEXT,                        -- 中文释义
  antonym       TEXT                         -- 反义词
);
CREATE INDEX IF NOT EXISTS idx_senses_word ON public.senses (word_id);

-- 4. 例句 / 搭配表
CREATE TABLE IF NOT EXISTS public.examples (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sense_id       BIGINT NOT NULL REFERENCES public.senses(id) ON DELETE CASCADE,
  parent_phrase  TEXT,                       -- 若例句隶属于某搭配，记录该搭配
  kind           TEXT DEFAULT 'sentence',    -- phrase / sentence
  usage_label    TEXT,
  en             TEXT,
  zh             TEXT,
  gloss          TEXT,                       -- (= die suddenly) 等注释
  source         TEXT                        -- 人教③-5 / 2009江西 等
);
CREATE INDEX IF NOT EXISTS idx_examples_sense ON public.examples (sense_id);

-- 5. 扫描批次表（记录每次拍照上传与解析状态）
CREATE TABLE IF NOT EXISTS public.scan_batches (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id       TEXT REFERENCES public.books(id) ON DELETE SET NULL,
  image_path    TEXT,                        -- Storage 中的文件路径
  image_url     TEXT,                        -- 公开/签名访问 URL
  page_no       INTEGER,
  status        TEXT DEFAULT 'pending',      -- pending / done / error
  words_found   INTEGER DEFAULT 0,
  error_msg     TEXT,
  raw_result    JSONB,                       -- AI 原始解析结果，便于回溯
  created_at    TIMESTAMPTZ DEFAULT now()
);

-- ============================================================
-- 6. 行级安全策略 (RLS)
--    查询端（背单词工具）只读开放；写入由 Edge Function 用 service_role 完成
-- ============================================================
ALTER TABLE public.books        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.words        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.senses       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.examples     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scan_batches ENABLE ROW LEVEL SECURITY;

-- 允许所有人读取（个人工具场景，如需登录可改为 auth.uid() 判断）
CREATE POLICY "public read books"        ON public.books        FOR SELECT USING (true);
CREATE POLICY "public read words"        ON public.words        FOR SELECT USING (true);
CREATE POLICY "public read senses"       ON public.senses       FOR SELECT USING (true);
CREATE POLICY "public read examples"     ON public.examples     FOR SELECT USING (true);
CREATE POLICY "public read scan_batches" ON public.scan_batches FOR SELECT USING (true);

-- 允许 anon 创建扫描批次（前端上传后登记）；其余写入走 service_role
CREATE POLICY "anon insert scan_batches" ON public.scan_batches FOR INSERT TO anon WITH CHECK (true);

-- ============================================================
-- 7. Storage：存放上传的页面照片
-- ============================================================
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('pages', 'pages', TRUE, 10485760, ARRAY['image/jpeg','image/png','image/webp','image/heic'])
ON CONFLICT (id) DO NOTHING;

-- 允许匿名上传图片到 pages 桶
CREATE POLICY "anon upload pages" ON storage.objects
  FOR INSERT TO anon WITH CHECK (bucket_id = 'pages');
-- 允许公开读取
CREATE POLICY "public read pages" ON storage.objects
  FOR SELECT USING (bucket_id = 'pages');

-- ============================================================
-- 8. 便于查询的联查视图：一条例句带出完整词条信息
-- ============================================================
CREATE OR REPLACE VIEW public.v_vocab AS
SELECT
  w.id AS word_id, w.headword, w.phonetic, w.level_tag, w.page_no,
  s.id AS sense_id, s.pos, s.sense_no, s.countability, s.usage_label AS sense_usage,
  s.chinese_def, s.antonym,
  e.id AS example_id, e.kind, e.parent_phrase, e.en, e.zh, e.gloss,
  e.source AS example_source
FROM public.words w
JOIN public.senses s   ON s.word_id = w.id
JOIN public.examples e ON e.sense_id = s.id;

