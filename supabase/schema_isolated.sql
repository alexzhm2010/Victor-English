-- ============================================================
-- 背单词工具 · 隔离版建表脚本（用于已有 words 表的生产项目）
-- 所有新表统一加 vw_ 前缀，与现有 words / dictionary_* 业务表完全隔离
-- 在 Supabase SQL Editor 执行，或通过 Management API 执行
-- ============================================================

-- 1. 书籍表
CREATE TABLE IF NOT EXISTS public.vw_books (
  id          TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  cover_url   TEXT,
  created_at  TIMESTAMPTZ DEFAULT now()
);

-- 2. 词条表
CREATE TABLE IF NOT EXISTS public.vw_words (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id       TEXT REFERENCES public.vw_books(id) ON DELETE CASCADE,
  headword      TEXT NOT NULL,
  phonetic      TEXT,
  audio         BOOLEAN DEFAULT FALSE,
  level_tag     TEXT,
  inline_def    TEXT,
  countability  TEXT,
  source        TEXT,
  page_no       INTEGER,
  batch_id      BIGINT,
  created_at    TIMESTAMPTZ DEFAULT now(),
  UNIQUE(book_id, headword)
);
CREATE INDEX IF NOT EXISTS idx_vw_words_headword ON public.vw_words (headword);
CREATE INDEX IF NOT EXISTS idx_vw_words_book ON public.vw_words (book_id);

-- 3. 义项表
CREATE TABLE IF NOT EXISTS public.vw_senses (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id       BIGINT NOT NULL REFERENCES public.vw_words(id) ON DELETE CASCADE,
  pos           TEXT,
  sense_no      INTEGER,
  countability  TEXT,
  usage_label   TEXT,
  chinese_def   TEXT,
  antonym       TEXT
);
CREATE INDEX IF NOT EXISTS idx_vw_senses_word ON public.vw_senses (word_id);

-- 4. 例句/搭配表
CREATE TABLE IF NOT EXISTS public.vw_examples (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sense_id       BIGINT NOT NULL REFERENCES public.vw_senses(id) ON DELETE CASCADE,
  parent_phrase  TEXT,
  kind           TEXT DEFAULT 'sentence',
  usage_label    TEXT,
  en             TEXT,
  zh             TEXT,
  gloss          TEXT,
  source         TEXT
);
CREATE INDEX IF NOT EXISTS idx_vw_examples_sense ON public.vw_examples (sense_id);

-- 5. 扫描批次表
CREATE TABLE IF NOT EXISTS public.vw_scan_batches (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id       TEXT REFERENCES public.vw_books(id) ON DELETE SET NULL,
  image_path    TEXT,
  image_url     TEXT,
  page_no       INTEGER,
  status        TEXT DEFAULT 'pending',
  words_found   INTEGER DEFAULT 0,
  error_msg     TEXT,
  raw_result    JSONB,
  created_at    TIMESTAMPTZ DEFAULT now()
);

-- ============================================================
-- 6. RLS
-- ============================================================
ALTER TABLE public.vw_books        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vw_words        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vw_senses       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vw_examples     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vw_scan_batches ENABLE ROW LEVEL SECURITY;

CREATE POLICY "vw public read books"        ON public.vw_books        FOR SELECT USING (true);
CREATE POLICY "vw public read words"        ON public.vw_words        FOR SELECT USING (true);
CREATE POLICY "vw public read senses"       ON public.vw_senses       FOR SELECT USING (true);
CREATE POLICY "vw public read examples"     ON public.vw_examples     FOR SELECT USING (true);
CREATE POLICY "vw public read scan_batches" ON public.vw_scan_batches FOR SELECT USING (true);
CREATE POLICY "vw anon insert scan_batches" ON public.vw_scan_batches FOR INSERT TO anon WITH CHECK (true);

-- ============================================================
-- 7. Storage bucket（独立命名，避免与业务桶冲突）
-- ============================================================
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('vocab-pages', 'vocab-pages', TRUE, 10485760, ARRAY['image/jpeg','image/png','image/webp','image/heic'])
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "vw anon upload" ON storage.objects
  FOR INSERT TO anon WITH CHECK (bucket_id = 'vocab-pages');
CREATE POLICY "vw public read images" ON storage.objects
  FOR SELECT USING (bucket_id = 'vocab-pages');

-- ============================================================
-- 8. 联查视图
-- ============================================================
CREATE OR REPLACE VIEW public.vw_vocab AS
SELECT
  w.id AS word_id, w.headword, w.phonetic, w.level_tag, w.page_no,
  s.id AS sense_id, s.pos, s.sense_no, s.countability, s.usage_label AS sense_usage,
  s.chinese_def, s.antonym,
  e.id AS example_id, e.kind, e.parent_phrase, e.en, e.zh, e.gloss,
  e.source AS example_source
FROM public.vw_words w
JOIN public.vw_senses s   ON s.word_id = w.id
JOIN public.vw_examples e ON e.sense_id = s.id;

