DROP POLICY IF EXISTS "vw public update words" ON public.vw_words;
CREATE POLICY "vw public update words" ON public.vw_words FOR UPDATE USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "vw public update senses" ON public.vw_senses;
CREATE POLICY "vw public update senses" ON public.vw_senses FOR UPDATE USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "vw public update examples" ON public.vw_examples;
CREATE POLICY "vw public update examples" ON public.vw_examples FOR UPDATE USING (true) WITH CHECK (true);

