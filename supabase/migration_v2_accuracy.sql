-- 1) vw_words：身份符号 + 词频级别 + 派生关联（真外键 + 文本兜底）
ALTER TABLE public.vw_words ADD COLUMN IF NOT EXISTS identity_tag TEXT;
ALTER TABLE public.vw_words ADD COLUMN IF NOT EXISTS freq_level SMALLINT;
ALTER TABLE public.vw_words ADD COLUMN IF NOT EXISTS derived_from TEXT;
ALTER TABLE public.vw_words ADD COLUMN IF NOT EXISTS parent_word_id BIGINT
  REFERENCES public.vw_words(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_vw_words_parent ON public.vw_words (parent_word_id);

COMMENT ON COLUMN public.vw_words.identity_tag  IS '身份符号: *课标外 / ⊕增补 / ⊖删减 / derived派生合成; NULL=普通课标词';
COMMENT ON COLUMN public.vw_words.freq_level    IS '词频级别 1..5 (对应 R¹..R⁵, 高考真题词频)';
COMMENT ON COLUMN public.vw_words.derived_from  IS '▶/▼派生词的母词词头文本, 如 attach; 用于核对与跨页兜底';
COMMENT ON COLUMN public.vw_words.parent_word_id IS '母词 id (真外键); 派生词指向主词条, 普通词 NULL';

-- 2) vw_senses：义项级英文释义 + 义项频次(深浅)
ALTER TABLE public.vw_senses ADD COLUMN IF NOT EXISTS english_def TEXT;
ALTER TABLE public.vw_senses ADD COLUMN IF NOT EXISTS sense_freq SMALLINT;
COMMENT ON COLUMN public.vw_senses.english_def IS '义项的斜体英文释义, 如 to make a serious request for sth';
COMMENT ON COLUMN public.vw_senses.sense_freq IS '义项频次: 1=高频(深色序号) 2=低频(浅色序号); NULL=未知';

-- 3) 新表 vw_notes：蓝底标签框（辨/注/同/句型）
CREATE TABLE IF NOT EXISTS public.vw_notes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id    BIGINT NOT NULL REFERENCES public.vw_words(id) ON DELETE CASCADE,
  note_type  TEXT NOT NULL,     -- 辨 / 注 / 同 / 句型
  title      TEXT,              -- 主题, 如 'assist, help, aid' / 'as, which'
  content    TEXT,              -- 框内文字(含项目符号/换行)
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_vw_notes_word ON public.vw_notes (word_id);
ALTER TABLE public.vw_notes ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "vw public read notes" ON public.vw_notes;
CREATE POLICY "vw public read notes" ON public.vw_notes FOR SELECT USING (true);

-- 4) 视图重建：补全部新字段
DROP VIEW IF EXISTS public.vw_vocab;
CREATE VIEW public.vw_vocab AS
SELECT
  w.id AS word_id, w.headword, w.phonetic, w.audio,
  w.identity_tag, w.freq_level, w.derived_from, w.parent_word_id,
  w.level_tag, w.inline_def, w.countability AS word_countability, w.source AS word_source,
  w.page_no, w.partial,
  s.id AS sense_id, s.pos, s.sense_no, s.countability, s.usage_label AS sense_usage,
  s.chinese_def, s.english_def, s.sense_freq, s.antonym,
  e.id AS example_id, e.kind, e.parent_phrase, e.usage_label AS example_usage,
  e.en, e.zh, e.gloss, e.source AS example_source
FROM public.vw_words w
JOIN public.vw_senses s   ON s.word_id = w.id
JOIN public.vw_examples e ON e.sense_id = s.id;

